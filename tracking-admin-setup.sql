-- 1. Nhật ký hoạt động
create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course text not null check (course in ('hsk1','hsk4')),
  lesson_no integer not null check (lesson_no > 0),
  activity_type text not null check (
    activity_type in ('lesson_open','game_score','lesson_complete')
  ),
  detail jsonb not null default '{}'::jsonb,
  activity_at timestamptz not null default now()
);

create index if not exists idx_activity_user_time
on public.activity_logs(user_id, activity_at desc);

create index if not exists idx_activity_course_lesson
on public.activity_logs(course, lesson_no, activity_at desc);

alter table public.activity_logs enable row level security;

drop policy if exists "activity_select_own" on public.activity_logs;
create policy "activity_select_own"
on public.activity_logs
for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "activity_insert_own" on public.activity_logs;
create policy "activity_insert_own"
on public.activity_logs
for insert
to authenticated
with check ((select auth.uid()) = user_id);


-- 2. Danh sách tài khoản giáo viên/quản trị
create table if not exists public.admin_users (
  id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

drop policy if exists "admin_users_select_own" on public.admin_users;
create policy "admin_users_select_own"
on public.admin_users
for select
to authenticated
using ((select auth.uid()) = id);


-- 3. Hàm kiểm tra quyền quản trị
create schema if not exists private;

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users a
    where a.id = (select auth.uid())
  );
$$;

revoke all on function private.is_admin() from public;
grant usage on schema private to authenticated;
grant execute on function private.is_admin() to authenticated;


