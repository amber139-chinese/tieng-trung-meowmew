-- 5. Bảng xếp hạng an toàn cho học sinh.
-- Chỉ công khai TÊN HIỂN THỊ + số liệu học tập tổng hợp.
-- Không đưa username, email hay user_id ra view này.
drop view if exists public.course_leaderboard;

create view public.course_leaderboard as
with
pstats as (
  select
    user_id,
    course,
    count(*) filter (where status = 'completed')::int as completed_lessons,
    count(*)::int as touched_lessons,
    round(coalesce(avg(best_score) filter (where best_score is not null),0))::int as avg_best_score,
    max(last_opened_at) as progress_last_active
  from public.lesson_progress
  group by user_id, course
),
gstats as (
  select
    user_id,
    course,
    count(*)::int as game_attempts,
    round(coalesce(avg(score),0))::int as avg_game_score,
    count(*) filter (where played_at >= now() - interval '7 days')::int as attempts_7d,
    count(distinct (played_at at time zone 'UTC')::date)
      filter (where played_at >= now() - interval '7 days')::int as active_days_7d,
    max(played_at) as game_last_active
  from public.game_results
  group by user_id, course
),
all_courses as (
  select user_id, course from pstats
  union
  select user_id, course from gstats
)
select
  pr.display_name,
  ac.course,
  coalesce(ps.completed_lessons,0)::int as completed_lessons,
  coalesce(ps.touched_lessons,0)::int as touched_lessons,
  coalesce(ps.avg_best_score,0)::int as avg_best_score,
  coalesce(gs.game_attempts,0)::int as game_attempts,
  coalesce(gs.avg_game_score,0)::int as avg_game_score,
  coalesce(gs.attempts_7d,0)::int as attempts_7d,
  coalesce(gs.active_days_7d,0)::int as active_days_7d,
  greatest(ps.progress_last_active, gs.game_last_active) as last_active,
  (
    coalesce(ps.completed_lessons,0) * 100
    + coalesce(ps.avg_best_score,0)
    + least(coalesce(gs.game_attempts,0),50)
  )::int as points
from all_courses ac
join public.profiles pr on pr.id = ac.user_id
left join pstats ps on ps.user_id = ac.user_id and ps.course = ac.course
left join gstats gs on gs.user_id = ac.user_id and gs.course = ac.course;

revoke all on public.course_leaderboard from anon;
grant select on public.course_leaderboard to authenticated;
